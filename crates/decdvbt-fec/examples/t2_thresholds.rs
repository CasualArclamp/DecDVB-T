//! The C/N each T2 FEC mode needs in a Gaussian channel with this decoder:
//! for every frame size, constellation (rotated or not) and code rate, the
//! lowest C/N at which twelve blocks in a row decode, found by bisection with
//! the cells' noise known exactly. Prints the table `t2/threshold.rs` holds.
//!
//! ```text
//! cargo run --release -p decdvbt-fec --example t2_thresholds
//! ```

use decdvbt_core::{CodeRate, FecFrame, Iq};
use decdvbt_fec::t2::plp::PlpCoder;
use decdvbt_fec::t2::qam::Qam;

const RATES: [(u16, u16); 6] = [(1, 2), (3, 5), (2, 3), (3, 4), (4, 5), (5, 6)];
const BLOCKS: usize = 12;

struct Rng(u32);

impl Rng {
    fn uniform(&mut self) -> f32 {
        self.0 = self.0.wrapping_mul(1664525).wrapping_add(1013904223);
        (self.0 >> 8) as f32 / (1u32 << 24) as f32
    }

    fn gauss(&mut self) -> f32 {
        (0..4).map(|_| self.uniform() - 0.5).sum::<f32>() * 1.732_050_8
    }
}

/// Whether `BLOCKS` blocks all decode at this C/N.
fn decodes(coder: &mut PlpCoder, cn_db: f64, rng: &mut Rng) -> bool {
    let sigma2 = 10f64.powf(-cn_db / 10.0) as f32;
    let sd = (sigma2 / 2.0).sqrt();
    let mut cells = Vec::new();
    for _ in 0..BLOCKS {
        let bb: Vec<u8> = (0..coder.bbframe_bytes())
            .map(|_| (rng.uniform() * 256.0) as u8)
            .collect();
        coder.encode(&bb, &mut cells);
        let noisy: Vec<Iq> = cells
            .iter()
            .map(|c| *c + Iq::new(rng.gauss() * sd, rng.gauss() * sd))
            .collect();
        let var = vec![sigma2; noisy.len()];
        let mut out = vec![0u8; bb.len()];
        match coder.decode(&noisy, &var, &mut out) {
            Some(st) if st.ldpc.converged && out == bb => {}
            _ => return false,
        }
    }
    true
}

fn main() {
    let mut rng = Rng(2024);
    println!("// Generated by crates/decdvbt-fec/examples/t2_thresholds.rs.");
    println!("pub(super) const CN_DB: [[[[f32; 6]; 4]; 2]; 2] = [");
    for frame in [FecFrame::Normal, FecFrame::Short] {
        println!("    [");
        for rotated in [false, true] {
            println!("        [");
            for qam in Qam::ALL {
                let mut row = Vec::new();
                for (n, d) in RATES {
                    let mut coder =
                        PlpCoder::new(frame, CodeRate::new(n, d), qam, rotated).expect("a code");
                    let (mut lo, mut hi) = (-3.0f64, 32.0f64);
                    while hi - lo > 0.1 {
                        let mid = 0.5 * (lo + hi);
                        if decodes(&mut coder, mid, &mut rng) {
                            hi = mid;
                        } else {
                            lo = mid;
                        }
                    }
                    row.push(format!("{:.1}", hi + 0.35));
                }
                println!("            [{}],", row.join(", "));
            }
            println!("        ],");
        }
        println!("    ],");
    }
    println!("];");
}
